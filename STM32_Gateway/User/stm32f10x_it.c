{
}

/**
  * @brief  This function handles Hard Fault exception.
  * @param  None
  * @retval None
  */
void HardFault_Handler(void)
{
  /* 记录现场到 Flash 保留页并复位。
     原来是 while(1) 死循环：现场表现就是"设备没反应，只能断电重启"，
     而且什么线索都留不下。 */
  FaultLog_Save(FAULT_KIND_HARD);
}

/**
  * @brief  This function handles Memory Manage exception.
  * @param  None
  * @retval None
  */
